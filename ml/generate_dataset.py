"""Generate the synthetic triage dataset used to train MedOS's priority model.

SYNTHETIC DATA — NOT REAL PATIENTS. Every row is generated by this script, so the dataset can be
shared freely and regenerated exactly (fixed random seed). It is built from the project's triage
protocol (medos/triage.py): the ten red flags and the 15-row priority table.

How a row is made
  1. Pick a condition with a realistic emergency-department mix (most visits are minor).
  2. Describe it the way patients talk: either one of the protocol's keywords, or an everyday
     paraphrase that is NOT in the keyword list ("my chest feels heavy", "can't catch my breath").
     Paraphrases are what let a learned model help where fixed keywords miss.
  3. Add context: duration, a second minor complaint, filler words, sometimes a negated symptom
     ("no chest pain") so the model has to learn that negation matters.
  4. Sample age, sex, pregnancy and vital signs. Most patients have normal vitals; some severe cases
     have abnormal ones, and some minor complaints come with dangerous vitals.
  5. Label = the priority a clinician applying the protocol would give: the condition's level, raised
     by danger-level vitals (SpO2 < 90, pulse >= 130 or <= 40, systolic BP < 90 → Critical, etc.) and
     by pregnancy with abdominal pain or bleeding. About 2% of labels are then shifted one level to
     simulate the disagreement between real clinicians.

Run:  python ml/generate_dataset.py            → ml/data/triage_synthetic.csv
"""
from __future__ import annotations

import csv
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from medos.triage import DEFAULT_CONDITIONS, LEVELS, LEVEL_ORDER  # noqa: E402

SEED = 2024
N_ROWS = 8000
OUT = ROOT / "ml" / "data" / "triage_synthetic.csv"

# Everyday ways of describing each condition that the keyword rules do NOT contain.
