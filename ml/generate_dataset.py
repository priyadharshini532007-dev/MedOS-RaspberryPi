UNCLASSIFIED = ["feeling tired and weak", "not feeling well since two days", "general weakness", "loss of appetite",
                "dizziness on standing", "pain in the leg muscles", "sleep problems"]

# Realistic mix: most emergency-department visits are minor.
LEVEL_SHARE = {"critical": 0.14, "high": 0.20, "medium": 0.24, "low": 0.42}

DURATIONS = ["since morning", "since yesterday", "for two days", "since last night", "for one week", "since an hour",
             "from evening", "for three days", "suddenly", ""]
TEMPLATES = ["{s} {d}", "having {s} {d}", "patient complains of {s} {d}", "{s}", "{s} {d}, {extra}",
             "my {who} has {s} {d}", "{s} {d} and {extra}", "came with {s} {d}"]
EXTRAS = ["mild cough", "slight headache", "feeling tired", "not eating well", "body pains", "a little nausea", "poor sleep"]
WHO = ["father", "mother", "son", "daughter", "husband", "wife", "grandmother", "neighbour"]
NEGATIONS = ["no chest pain", "no breathing difficulty", "no vomiting", "no fever", "not unconscious", "no bleeding"]

# Prefix keywords in the protocol end in '*': give them a natural ending for the text.
STAR_ENDINGS = {"wheez": "wheezing", "dislocat": "dislocated shoulder", "dehydrat": "dehydrated", "breath": "breathing",
                "difficult": "difficulty", "slurr": "slurred speech", "droop": "drooping", "blu": "blue", "sneez": "sneezing",
                "tight": "tightness", "squeez": "squeezing", "bit": "bitten", "swell": "swelling", "burn": "burns",
                "pain": "pain"}


def keyword_text(kw: str) -> str:
    """Turn a protocol keyword ('chest+tight*', 'wheez*') into words a patient would say."""
    parts = []
    for p in kw.split("+"):
        p = p.strip()
        if p.endswith("*"):
            p = STAR_ENDINGS.get(p[:-1], p[:-1])
        parts.append(p)
    return " ".join(parts)


def sample_vitals(rnd: random.Random, level: str, cond: str) -> dict:
    v = {}
    if rnd.random() < 0.6:   # vitals recorded for most patients
        sick = {"critical": 0.45, "high": 0.2, "medium": 0.08, "low": 0.02}[level]
        v["temp"] = round(rnd.gauss(98.6, 0.7), 1)
        v["pulse"] = int(rnd.gauss(84, 10))
        v["spo2"] = int(min(100, rnd.gauss(97.5, 1.2)))
        v["bp_sys"] = int(rnd.gauss(124, 14))
        if "fever" in cond.lower():
            v["temp"] = round(rnd.uniform(102.2, 104.5) if "High" in cond else rnd.uniform(99.5, 101.4), 1)
        if rnd.random() < sick:   # some severe cases come with abnormal vitals
            which = rnd.choice(["spo2", "pulse", "bp_sys", "pulse_low"])
            if which == "spo2":
                v["spo2"] = rnd.randint(78, 93)
            elif which == "pulse":
                v["pulse"] = rnd.randint(115, 160)
            elif which == "pulse_low":
                v["pulse"] = rnd.randint(32, 50)
            else:
                v["bp_sys"] = rnd.randint(70, 95) if rnd.random() < 0.6 else rnd.randint(180, 210)
    if rnd.random() < 0.35:
        hurt = {"critical": (6, 10), "high": (5, 10), "medium": (3, 8), "low": (1, 5)}[level]
        v["pain"] = rnd.randint(*hurt)
    return v


def label_for(level: str, cond_name: str, text: str, vitals: dict, age: int, pregnant: bool) -> str:
    """The priority a clinician applying the protocol would assign."""
    order = LEVEL_ORDER

    def raise_to(cur: str, new: str) -> str:
        return new if order[new] < order[cur] else cur

    spo2, pulse, bp, temp, pain = (vitals.get(k) for k in ("spo2", "pulse", "bp_sys", "temp", "pain"))
    if spo2 is not None:
        level = raise_to(level, "critical" if spo2 < 90 else "high" if spo2 < 94 else level)
    if pulse is not None:
        level = raise_to(level, "critical" if pulse >= 130 or pulse <= 40 else "medium" if pulse > 110 else level)
    if bp is not None:
        level = raise_to(level, "critical" if bp < 90 else "high" if bp >= 180 else level)
    if temp is not None and temp >= 104:
        level = raise_to(level, "high")
    if temp is not None and temp >= 102:
        level = raise_to(level, "high")
    if pain is not None and pain >= 8:
        level = raise_to(level, "medium")
    if pregnant and (cond_name in ("Severe abdominal pain", "Stomach pain (mild)") or "bleeding" in text):
        level = raise_to(level, "high")
    return level


def make_row(rnd: random.Random, by_level: dict) -> dict:
    level = rnd.choices(LEVELS, weights=[LEVEL_SHARE[x] for x in LEVELS])[0]
    if level == "low" and rnd.random() < 0.06:
        cond, name, kind = None, "Unclassified complaint", "unclassified"
        phrase = rnd.choice(UNCLASSIFIED)
    else:
        cond = rnd.choice(by_level[level])
        name = cond["name"]
        # 45% protocol keyword, 55% everyday paraphrase the rules don't know
        if rnd.random() < 0.45 or not PARAPHRASES.get(name):
            phrase, kind = keyword_text(rnd.choice(cond["keywords"])), "keyword"
        else:
            phrase, kind = rnd.choice(PARAPHRASES[name]), "paraphrase"
    tpl = rnd.choice(TEMPLATES)
    text = tpl.format(s=phrase, d=rnd.choice(DURATIONS), extra=rnd.choice(EXTRAS), who=rnd.choice(WHO))
    if rnd.random() < 0.08:
        text += ", " + rnd.choice(NEGATIONS)
    text = " ".join(text.split()).strip(" ,")
    text = text[0].upper() + text[1:]

    child = name in ("Ear pain",) and rnd.random() < 0.5
    age = rnd.randint(1, 12) if child else max(1, min(92, int(rnd.gauss(42, 20))))
    sex = rnd.choice(["male", "female"])
    pregnant = sex == "female" and 18 <= age <= 42 and rnd.random() < 0.08
    vitals = sample_vitals(rnd, level, name)
    label = label_for(level, name, text.lower(), vitals, age, pregnant)
    if rnd.random() < 0.02:   # clinicians don't always agree: shift a few labels by one level
        i = LEVELS.index(label) + rnd.choice([-1, 1])
        label = LEVELS[max(0, min(3, i))]
    return {"symptoms": text, "age": age, "sex": sex, "pregnant": int(pregnant),
            "temp": vitals.get("temp", ""), "pulse": vitals.get("pulse", ""), "spo2": vitals.get("spo2", ""),
            "bp_sys": vitals.get("bp_sys", ""), "pain": vitals.get("pain", ""),
            "condition": name, "phrasing": kind,
            "priority": label}


def main() -> None:
    rnd = random.Random(SEED)
    by_level = {lvl: [c for c in DEFAULT_CONDITIONS if c["level"] == lvl] for lvl in LEVELS}
    rows = [make_row(rnd, by_level) for _ in range(N_ROWS)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    counts = {lvl: sum(r["priority"] == lvl for r in rows) for lvl in LEVELS}
    print("Wrote %d synthetic rows to %s" % (len(rows), OUT.relative_to(ROOT)))
    print("Priority mix: " + ", ".join("%s %d" % (k, v) for k, v in counts.items()))


if __name__ == "__main__":
    main()
